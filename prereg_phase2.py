# P9.3. Across-seed variance of gru128, low against high. A factor of 2 is the
# threshold: at 5 seeds a single pair of variances is too noisy to call at any
# smaller ratio, so the rule pools four cells per side (2 lambdas x 2 variants)
# AND additionally requires the ordering to hold within each variant separately.
P93_LOW_LAMBDAS = [0.8, 0.9]
P93_HIGH_LAMBDAS = [0.99, 1.0]
