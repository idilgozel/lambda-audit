        hi_b = _boot_group_mean(rng, high)
        diffs = [a - b for a, b in zip(lo_b, hi_b)]
        point = (sum(sum(c) / len(c) for c in low) / len(low)
                 - sum(sum(c) / len(c) for c in high) / len(high))
        lo_ci = _percentile(diffs, (100 - E9_CI) / 2)
        hi_ci = _percentile(diffs, 100 - (100 - E9_CI) / 2)
        good = point < 0 and hi_ci < 0
        ok91 = ok91 and good
        detail91.append(
            f"{env}: step {point:+.4f}, {E9_CI:.0f}% CI "
            f"[{lo_ci:+.4f}, {hi_ci:+.4f}] "
            f"({'negative and excludes zero' if good else 'DOES NOT QUALIFY'})")
