def iqm(xs):
    """Interquartile mean, identical in definition to the pilot's."""
    xs = sorted(xs)
    n = len(xs)
    lo, hi = n // 4, n - n // 4
    mid = xs[lo:hi] if hi > lo else xs
    return sum(mid) / len(mid)


def load_results(path):
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def cell(rows, instance, arm, lam, field):
    """Values of one field over the seeds of one cell."""
    out = []
    for r in rows:
        if r.get("seed") not in SEEDS:
            continue
        if r.get("arm", "coupled") != arm:
            continue
        base = str(r.get("env", "")).replace("_dec", "")
        if base != instance:
            continue
        if not math.isclose(float(r.get("lam", -1)), lam):
            continue
        v = r.get(field)
        if v is not None and math.isfinite(float(v)):
            out.append(float(v))
    return out


def _log_closer(x, a, b):
    """True if x is nearer a than b on a log scale. Guards non-positive x."""
    if x <= 0 or a <= 0 or b <= 0:
        return abs(x - a) < abs(x - b)
    return abs(math.log(x) - math.log(a)) < abs(math.log(x) - math.log(b))


def score_e6(rows, verbose=True):
    _assert_frozen()
    inst = E6_INSTANCE
    kml = BASELINES[inst]["k_ml"]
    jml = BASELINES[inst]["J_ml"]
    v = {}

    def g(arm, lam, field):
        c = cell(rows, inst, arm, lam, field)
        return iqm(c) if c else None

    # -- P6.1 ---------------------------------------------------------------
    ok61, detail61 = True, []
    for lam in P61_BELOW_LAMBDAS:
        i = LAMBDAS.index(lam)
        k_ref, j_ref = K_AC_LAMBDA[inst][i], J_AC_LAMBDA[inst][i]
        k_obs, j_obs = g("coupled", lam, "final_gain"), g("coupled", lam, "J_rate")
        if k_obs is None or j_obs is None:
            ok61 = False
            detail61.append(f"lambda {lam}: MISSING")
            continue
        near = _log_closer(k_obs, k_ref, kml)
        within = abs(j_obs - j_ref) / j_ref <= P61_J_TOLERANCE
        ok61 = ok61 and near and within
        detail61.append(
            f"lambda {lam}: gain {k_obs:.3f} vs k_AC {k_ref:.3f} "
            f"({'nearer k_AC' if near else 'NEARER k_ml'}), "
            f"J {j_obs:.4f} vs {j_ref:.4f} "
            f"({100 * abs(j_obs - j_ref) / j_ref:.1f}%, "
            f"{'within' if within else 'OUTSIDE'} {int(100 * P61_J_TOLERANCE)}%)")
    v["P6.1"] = ok61

    # -- P6.2 ---------------------------------------------------------------
    k1, j1 = g("coupled", 1.0, "final_gain"), g("coupled", 1.0, "J_rate")
    j_ref09 = g("coupled", P62_REF_LAMBDA, "J_rate")
    k_ref09 = K_AC_LAMBDA[inst][LAMBDAS.index(P62_REF_LAMBDA)]
    if None in (k1, j1, j_ref09):
        v["P6.2"] = None
        detail62 = "MISSING cells"
    else:
        near_ml = _log_closer(k1, kml, k_ref09)
        ratio = j_ref09 / j1 if j1 else float("nan")
        v["P6.2"] = bool(near_ml and ratio >= P62_MIN_EXCESS_RATIO)
        detail62 = (f"gain at 1.0 {k1:.3f} vs k_ml {kml:.3f} "
                    f"({'nearer k_ml' if near_ml else 'NEARER k_AC(0.9)'}), "
                    f"J(1.0) {j1:.4f} vs J_ml {jml:.4f}, "
                    f"excess ratio J(0.9)/J(1.0) = {ratio:.3f} "
                    f"(>= {P62_MIN_EXCESS_RATIO})")

    # -- P6.3 ---------------------------------------------------------------
    dec = [(lam, g("decoupled", lam, "final_gain")) for lam in LAMBDAS]
    have = [(lam, x) for lam, x in dec if x is not None]
    if not have:
        v["P6.3"] = None
        detail63 = "MISSING cells"
    else:
        worst = max(abs(x) for _, x in have)
        spread = max(x for _, x in have) - min(x for _, x in have)
        v["P6.3"] = bool(worst <= P63_GAIN_TOL and spread <= P63_GAIN_SPREAD)
        detail63 = (f"largest |gain| {worst:.4f} (<= {P63_GAIN_TOL}), "
                    f"spread across lambda {spread:.4f} (<= {P63_GAIN_SPREAD}), "
                    f"{len(have)}/{len(LAMBDAS)} lambdas present")

    # -- P6.4 ---------------------------------------------------------------
    def arm_diff(lam):
        a, b = g("coupled", lam, "final_gain"), g("decoupled", lam, "final_gain")
        return None if None in (a, b) else abs(a - b)

    d09, d10 = arm_diff(0.9), arm_diff(1.0)
