def duplicate_cells(rows):
    """(env, arch, lambda, seed) keys appearing more than once. Empty is clean.

    env carries the arm, since the decoupled arm is a distinct env id, so
    coupled and decoupled rows never collide with each other.

    CORRECTED 2026-08-14, before E9 was scored. The key first omitted arch,
    which is unique within E6 and E7 because both are mlp only, but E9 runs
    mlp and gru128 in the same environment. That made the guard report 80
    false duplicates on legitimate E9 data and refuse to score it. A guard
    that blocks correct data is as damaging as one that misses bad data.
    """
    counts = {}
    for r in rows:
        try:
            key = (str(r.get("env", "")), str(r.get("arch", "")),
                   round(float(r.get("lam")), 6), int(r.get("seed")))
        except (TypeError, ValueError):
            continue
        counts[key] = counts.get(key, 0) + 1
    return {k: n for k, n in counts.items() if n > 1}


def _percentile(xs, p):
    xs = sorted(xs)
    if not xs:
        return float("nan")
    i = (len(xs) - 1) * p / 100.0
    lo, hi = int(i), min(int(i) + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def _boot_group_mean(rng, cells, n=E9_BOOTSTRAP_N):
    """Bootstrap the mean of per cell IQMs, resampling seeds within each cell."""
    out = []
    for _ in range(n):
        vals = []
        for c in cells:
            draw = [c[rng.randrange(len(c))] for _ in range(len(c))]
            vals.append(iqm(draw))
        out.append(sum(vals) / len(vals))
    return out


def _e9_cell(rows, env, arch, lam):
    vals = []
    for r in rows:
        if (r.get("env") == env and r.get("arch") == arch
                and r.get("seed") in SEEDS
                and math.isclose(float(r.get("lam", -1)), lam)):
            v = r.get("deployed_return")
            if v is not None and math.isfinite(float(v)):
                vals.append(float(v))
    return vals


def _variance(xs):
    if len(xs) < 2:
        return float("nan")
    m = sum(xs) / len(xs)
    return sum((x - m) ** 2 for x in xs) / (len(xs) - 1)


def score_e9(rows, verbose=True):
    """CONDITIONAL. Frozen 2026-08-13 before any E9 data existed."""
    _assert_frozen()
    import random
    v = {}

    # -- P9.1, the step replicates in sign on both variants -----------------
    ok91, detail91 = True, []
    for env in E9_ENVS:
        low = [_e9_cell(rows, env, "mlp", l) for l in P91_LOW_LAMBDAS]
        high = [_e9_cell(rows, env, "mlp", l) for l in P91_HIGH_LAMBDAS]
