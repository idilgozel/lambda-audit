def measured_lambda_half(rows, instance):
    """Lambda where excess cost has fallen halfway from plateau to floor.

    Linear interpolation on the lambda grid. The plateau is the largest cell
    value and the floor the smallest, both measured, so this is a measurement
    and not a fit to the predicted location.
    """
    pts = []
    for lam in LAMBDAS:
        c = cell(rows, instance, "coupled", lam, "excess_cost")
        if c:
            pts.append((lam, iqm(c)))
    if len(pts) < 3:
        return None
    hi = max(x for _, x in pts)
    lo = min(x for _, x in pts)
    if hi - lo < 1e-9:
        return None
    mid = 0.5 * (hi + lo)
    for (l0, v0), (l1, v1) in zip(pts, pts[1:]):
        if (v0 - mid) * (v1 - mid) <= 0 and abs(v1 - v0) > 1e-12:
            return l0 + (mid - v0) * (l1 - l0) / (v1 - v0)
    return None


