#!/bin/bash -l
# Discover a working Python + torch environment on Myriad, prove it runs the
# harness, and record the recipe in env.sh for the job script to source.
#
# Design principle: DISCOVER, DO NOT ASSUME. Earlier attempts hardcoded module
# names and failed repeatedly (gcc-libs conflicts, Intel compiler builds of
# numpy, missing wheels). This script tries a ranked list of recipes in
# subshells, keeps the first one that actually imports torch AND trains the
# harness to a known-good score, and writes that recipe down.
#
# Requires only torch and numpy. The environments are provided by
# envs_native.py, a bitwise-verified reimplementation of the POPGym originals,
# so there is nothing to pip install and nothing to compile.
#
# Idempotent. Safe to re-run any number of times.
# Usage:  bash bootstrap_myriad.sh        (or ./bootstrap_myriad.sh)

set -uo pipefail
cd "$(dirname "$0")"
HERE="$PWD"
mkdir -p logs results smoke

echo "=============================================================="
echo " lambda-audit bootstrap"
echo " host: $(hostname)   dir: $HERE"
echo "=============================================================="

# File check first. It needs nothing, and a missing file is the likelier
# failure, so it should always produce the clearer message.
echo
echo "--- files present"
missing=0
for f in ppo_lambda.py envs_native.py configs_pilot.txt configs_capability.txt pilot_array.qsub.sh; do
  if [ -r "$f" ] && [ -s "$f" ]; then
    printf "    ok  %7d  %s\n" "$(wc -c < "$f")" "$f"
  else
    echo "    MISSING OR EMPTY: $f"
    missing=1
  fi
done
if [ "$missing" -ne 0 ]; then
  echo
  echo "FATAL: the package is incomplete here. Re-run deploy.sh from the Mac."
  echo "       Current directory: $HERE"
  exit 1
fi

# make `module` available even under a non-login shell
if ! command -v module >/dev/null 2>&1; then
  for f in /etc/profile.d/modules.sh /usr/share/Modules/init/bash /etc/profile.d/lmod.sh; do
    if [ -r "$f" ]; then . "$f"; break; fi
  done
fi
if ! command -v module >/dev/null 2>&1; then
  echo
  echo "FATAL: the 'module' command is unavailable even after sourcing the"
  echo "       usual init scripts. Run this as: bash -l bootstrap_myriad.sh"
  exit 1
fi

# Ranked candidate recipes. First one that works wins.
# UCL's pytorch modules supply torch AND a matching numpy, which is why they
# are preferred: no pip, no compiler, no numpy ABI mismatch.
declare -a NAMES=(
  "pytorch/2.1.0/cpu (clean)"
  "pytorch/2.1.0/cpu (defaults, gcc-libs swapped)"
  "pytorch/1.11.0/cpu (clean)"
  "pytorch/1.2.0/cpu (clean)"
  "python3/3.11 with existing torch"
  "python3/recommended with existing torch"
)
declare -a RECIPES=(
  "module purge; module load pytorch/2.1.0/cpu"
  "module purge; module load default-modules; module unload gcc-libs; module load pytorch/2.1.0/cpu"
  "module purge; module load pytorch/1.11.0/cpu"
  "module purge; module load pytorch/1.2.0/cpu"
  "module purge; module load python3/3.11"
  "module purge; module load python3/recommended"
)

WINNER=""
WINNER_NAME=""
echo
echo "--- probing environments (torch + numpy import)"
for i in "${!RECIPES[@]}"; do
  name="${NAMES[$i]}"
  recipe="${RECIPES[$i]}"
  out=$(
    (
      eval "$recipe" >/dev/null 2>&1
      unset CC CXX
      python3 - <<'PY' 2>/dev/null
import torch, numpy, sys
print(f"torch {torch.__version__} | numpy {numpy.__version__} | python {sys.version.split()[0]}")
PY
    ) 2>/dev/null
  )
  if [ -n "$out" ]; then
    echo "    WORKS   $name"
    echo "            $out"
    if [ -z "$WINNER" ]; then WINNER="$recipe"; WINNER_NAME="$name"; fi
  else
    echo "    no      $name"
  fi
done

if [ -z "$WINNER" ]; then
  echo
  echo "FATAL: no candidate environment provided torch."
  echo "Run 'module avail 2>&1 | grep -i torch' and send the output."
  exit 1
fi

echo
echo "--- selected: $WINNER_NAME"

cat > env.sh <<EOF
# Generated by bootstrap_myriad.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Selected recipe: $WINNER_NAME
# Source this from the job script. Do not hand edit; re-run the bootstrap.
if ! command -v module >/dev/null 2>&1; then
  for f in /etc/profile.d/modules.sh /usr/share/Modules/init/bash /etc/profile.d/lmod.sh; do
    if [ -r "\$f" ]; then . "\$f"; break; fi
  done
fi
$WINNER
unset CC CXX
export OMP_NUM_THREADS=1
export MKL_NUM_THREADS=1
EOF
echo "    wrote env.sh"

echo
echo "--- smoke test (about a minute): RepeatPreviousEasy, stack8, lambda 1.0"
echo "    random play scores about -0.54; this must exceed 0.90"
(
  set -e
  . ./env.sh
  python3 ppo_lambda.py --env RepeatPreviousEasy --arch stack8 --gae-lambda 1.0 \
      --seed 1 --total-timesteps 600000 --eval-every 50 --eval-episodes 10 \
      --final-eval-episodes 30 --out-dir smoke --run-name bootstrap_smoke
) > smoke/bootstrap_smoke.out 2>&1
rc=$?
tail -n 3 smoke/bootstrap_smoke.out | sed 's/^/    /'

if [ "$rc" -ne 0 ]; then
  echo
  echo "FATAL: the smoke run failed. Full output in smoke/bootstrap_smoke.out"
  exit 1
fi

VERDICT=$(
  . ./env.sh
  python3 - <<'PY'
import json, sys
best = None
try:
    for line in open("smoke/results_lambda_pilot.jsonl"):
        line = line.strip()
        if not line:
            continue
        r = json.loads(line)
        if r.get("run") == "bootstrap_smoke":
            best = r
except FileNotFoundError:
    pass
if best is None:
    print("NO_RESULT")
else:
    print("PASS" if best["deployed_return"] > 0.90 else "FAIL")
    print(f'deployed_return={best["deployed_return"]:.4f}')
PY
)
echo
echo "$VERDICT" | sed 's/^/    /'

if echo "$VERDICT" | head -1 | grep -q PASS; then
  touch bootstrap_ok
  echo
  echo "=============================================================="
  echo " BOOTSTRAP OK. env.sh is written and proven."
  echo " Next: submit the capability job."
  echo "   qsub -N lam_cap -t 1-2 -v CFG=configs_capability.txt,SEED_OFFSET=100 pilot_array.qsub.sh"
  echo "=============================================================="
  exit 0
else
  rm -f bootstrap_ok
  echo
  echo "FATAL: smoke score too low or missing. Nothing is broken on the"
  echo "cluster; send smoke/bootstrap_smoke.out and we will read it."
  exit 1
fi
