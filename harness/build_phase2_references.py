#!/usr/bin/env python3
"""Generate the Phase 2 reference values by RUNNING the GLEAM sources.

LOCAL ONLY, needs scipy. Nothing here is copied from phase2-design.md. Every
number is produced by executing lstd_lambda.py and gleam_bench.py, then
compared against the design doc, with any discrepancy reported loudly.

Output is a block of Python literals to paste into prereg_phase2.py, so the
preregistration holds frozen constants rather than a live computation. That is
the E4 lesson: frozen values live in an executable file, never recomputed at
scoring time where a dependency change could move them.

  k_AC(lambda)  the GAE(lambda) actor equilibrium gain, from lstd_lambda's
                k_eq_lambda, which roots the exact expected GAE gradient.
  lambda_half   the lambda at which k_AC has fallen halfway from its
                below-horizon plateau to k_ml, in log gain, found by bisection
                on the same exact function.

theorem2_learning.py keeps H, BETA and CC as module globals and lstd_lambda.py
reads them, so each instance is evaluated by setting those globals first. The
disc_model cache is keyed on (gamma, H), so this is safe. Verified below by
re-deriving instance one twice, once before and once after the others.

Run:  python3 harness/build_phase2_references.py
"""

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "vendor", "gleam"))

import theorem2_learning as T          # noqa: E402
import lstd_lambda as L                # noqa: E402
from gleam_bench import GLEBench       # noqa: E402

LAMBDAS = [0.8, 0.9, 0.95, 0.98, 0.99, 0.995, 0.999, 1.0]
INSTANCES = [
    ("GLEAM_g1_h0.05", 0.3, 1.0, 0.05),
    ("GLEAM_g1_h0.02", 0.3, 1.0, 0.02),
    ("GLEAM_g2_h0.05", 0.3, 2.0, 0.05),
    ("GLEAM_g4_h0.05", 0.3, 4.0, 0.05),
]
S_E = 0.3 ** 2


def set_instance(c, gamma, h):
    """Point the vendored modules at one instance. Globals, deliberately."""
    T.H = h
    T.BETA = float(np.exp(-T.RHO * h))
    T.CC = c
    return T.BETA


def k_ac_of_lambda(gamma, lam):
    """Largest root of the exact expected GAE gradient, or nan."""
    roots = L.k_eq_lambda(gamma, S_E, lam)
    if not roots:
        return float("nan")
    return float(max(roots))


def lambda_half(gamma, k_lo, k_ml, tol=1e-4):
    """Lambda where k_AC has fallen halfway from its plateau to k_ml.

    Halfway is taken in log gain, since the collapse spans more than an order
    of magnitude and a linear midpoint would sit almost on top of the plateau.
    Bisection on lambda, using the same exact k_AC function as everywhere else.
    """
    if not np.isfinite(k_lo) or k_lo <= k_ml:
        return float("nan")
    target = float(np.sqrt(k_lo * k_ml))       # geometric mean = log midpoint
    lo, hi = 0.5, 1.0
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        k = k_ac_of_lambda(gamma, mid)
        if not np.isfinite(k):
            k = k_ml
        if k > target:
            lo = mid
        else:
            hi = mid
        if hi - lo < tol:
            break
    return 0.5 * (lo + hi)


def main():
    print("=" * 78)
    print(" Phase 2 reference values, generated by running lstd_lambda.py")
    print("=" * 78)

    k_ac = {}
    j_ac = {}
    lam_half = {}
    ml = {}
    betas = {}
    first_pass_check = None

    for name, c, gamma, h in INSTANCES:
        beta = set_instance(c, gamma, h)
        betas[name] = beta
        env = GLEBench(cs=(c,), gammas=(gamma,), theta=1.0, h=h,
                       q=1.0, r=1.0, rho=0.05, n_envs=1, seed=0)
        b = env.baselines(s_e=S_E)
        ml[name] = (b["k_ml"], b["J_ml"], b["J_opt"], b["rThK0"])

        print(f"\n--- {name}   gamma={gamma} h={h} gamma*h={gamma * h:.3f} "
              f"beta={beta:.8f}")
        print(f"    k_ml={b['k_ml']:.4f}  J_ml={b['J_ml']:.4f}  "
              f"k_AC(TD0)={b['k_AC']:.4f}")
        row, jrow = [], []
        for lam in LAMBDAS:
            k = k_ac_of_lambda(gamma, lam)
            # J at that equilibrium gain, deployed, no exploration noise. This
            # is what P6.1 scores the measured cost against, so it has to be
            # J(k_AC(lambda)) and not the TD(0) J_AC from the baseline table.
            j = float(env.J_gain(k)) if np.isfinite(k) else float("nan")
            row.append(k)
            jrow.append(j)
            print(f"    lambda={lam:<6} k_AC={k:10.4f}  J(k_AC)={j:8.4f}"
                  + ("   <- no root in range" if not np.isfinite(k) else ""))
        k_ac[name] = row
        j_ac[name] = jrow
        lam_half[name] = lambda_half(gamma, row[0], b["k_ml"])
        print(f"    lambda_half = {lam_half[name]:.5f}")
        if name == "GLEAM_g1_h0.05":
            first_pass_check = list(row)

    # Guard against the documented stale-cache class of bug: re-derive the
    # first instance after the others have moved the globals around.
    set_instance(0.3, 1.0, 0.05)
    redo = [k_ac_of_lambda(1.0, lam) for lam in LAMBDAS]
    same = all(
        (np.isnan(a) and np.isnan(b)) or abs(a - b) < 1e-9
        for a, b in zip(first_pass_check, redo))
    print(f"\n--- global-mutation guard: instance one re-derived after the "
          f"others {'MATCHES' if same else 'DIFFERS, STOP'}")

    print("\n" + "=" * 78)
    print(" Comparison against phase2-design.md")
    print("=" * 78)
    issues = []
    # Design doc section 3: E4 located lambda_half at 0.98541 for the default
    # instance. Section 4 P6.1 quotes k_AC = 24.79 at lambda 0.9.
    k09 = k_ac["GLEAM_g1_h0.05"][LAMBDAS.index(0.9)]
    print(f"  k_AC(0.9) on the default instance: generated {k09:.4f}, "
          f"design doc says 24.79")
    if np.isfinite(k09) and abs(k09 - 24.79) > 0.05:
        issues.append(f"k_AC(0.9) generated {k09:.4f} vs design doc 24.79")
    lh = lam_half["GLEAM_g1_h0.05"]
    print(f"  lambda_half on the default instance: generated {lh:.5f}, "
          f"E4 measured 0.98541")
    if np.isfinite(lh) and abs(lh - 0.98541) > 0.01:
        issues.append(f"lambda_half generated {lh:.5f} vs E4 0.98541")

    print("\n  P7.2, lambda_half monotone decreasing in gamma*h:")
    order = sorted(INSTANCES, key=lambda t: t[2] * t[3])
    prev = None
    mono = True
    for name, c, gamma, h in order:
        v = lam_half[name]
        flag = ""
        if prev is not None and not (v < prev + 1e-9):
            flag = "   <- NOT decreasing"
            mono = False
        print(f"    gamma*h={gamma * h:.3f}  {name:16} lambda_half={v:.5f}{flag}")
        prev = v
    print(f"    monotone: {'yes' if mono else 'NO'}")

    if issues:
        print("\n  DISCREPANCIES, reported loudly:")
        for i in issues:
            print(f"    {i}")
    else:
        print("\n  no discrepancies against the design doc")

    print("\n" + "=" * 78)
    print(" Literals for prereg_phase2.py")
    print("=" * 78)
    print("\nLAMBDAS = " + repr(LAMBDAS))
    print("\nBETA = {")
    for n, v in betas.items():
        print(f"    {n!r}: {v!r},")
    print("}")
    print("\nK_AC_LAMBDA = {")
    for n, row in k_ac.items():
        print(f"    {n!r}: [" + ", ".join(f"{v:.6f}" for v in row) + "],")
    print("}")
    print("\nJ_AC_LAMBDA = {")
    for n, row in j_ac.items():
        print(f"    {n!r}: [" + ", ".join(f"{v:.6f}" for v in row) + "],")
    print("}")
    print("\nLAMBDA_HALF = {")
    for n, v in lam_half.items():
        print(f"    {n!r}: {v:.6f},")
    print("}")
    print("\nBASELINES = {")
    for n, (kml, jml, jopt, law) in ml.items():
        print(f"    {n!r}: dict(k_ml={kml:.6f}, J_ml={jml:.6f}, "
              f"J_opt={jopt:.6f}, rThK0={law:.6f}),")
    print("}")
    return 0 if (same and not issues) else 1


if __name__ == "__main__":
    sys.exit(main())
