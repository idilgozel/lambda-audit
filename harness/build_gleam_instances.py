#!/usr/bin/env python3
"""Precompute the GLEAM instance constants and write gleam_instances.npz.

LOCAL ONLY. This needs scipy, which never goes on Myriad. Everything scipy is
needed for lives here: expm for the exact ZOH discretisation, the Lyapunov and
Riccati solves for the baselines, and the two cholesky factors. The cluster
then steps the environment with numpy alone.

The matrices are taken straight off a constructed GLEBench instance rather
than recomputed, so what ships is bit for bit what the reference environment
uses. That is what makes the equivalence test in test_gleam_equivalence.py
able to assert bitwise identity rather than closeness.

Run:  python3 harness/build_gleam_instances.py
"""

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "vendor", "gleam"))

from gleam_bench import GLEBench  # noqa: E402

# (id, c, gamma, h). Required by phase2-design.md section 4. gamma*h is the
# knob that places the critical horizon: 0.05, 0.02, 0.10, 0.20.
INSTANCES = [
    ("GLEAM_g1_h0.05", 0.3, 1.0, 0.05),
    ("GLEAM_g1_h0.02", 0.3, 1.0, 0.02),
    ("GLEAM_g2_h0.05", 0.3, 2.0, 0.05),
    ("GLEAM_g4_h0.05", 0.3, 4.0, 0.05),
]

THETA, Q, R, RHO = 1.0, 1.0, 1.0, 0.05
S_E = 0.3 ** 2          # exploration noise variance used by the AC baselines
EPISODE_LEN = 1024      # matches gleam_gym.py

# The design doc's table, for the loud comparison demanded by the protocol.
# Keyed by instance id. Values are J_opt, k_ml, J_ml, k_AC, J_AC.
DESIGN_DOC_TABLE = {
    "GLEAM_g1_h0.05": (0.1989, 1.649, 0.2196, 24.794, 0.2964),
    "GLEAM_g1_h0.02": (0.1973, 1.664, 0.2175, 63.506, 0.2987),
    "GLEAM_g2_h0.05": (0.1552, 1.347, 0.1720, 23.920, 0.2959),
    "GLEAM_g4_h0.05": (0.1044, 1.158, 0.1130, 22.006, 0.2874),
}


def build():
    out = {}
    names = []
    print("=" * 78)
    print(" GLEAM instance constants, generated by running gleam_bench.py")
    print("=" * 78)
    print(f"\n{'instance':16} {'J_opt':>8} {'k_ml':>8} {'J_ml':>8} "
          f"{'k_AC':>9} {'J_AC':>8} {'rThK0':>8}")

    discrepancies = []
    for name, c, gamma, h in INSTANCES:
        env = GLEBench(cs=(c,), gammas=(gamma,), theta=THETA, h=h,
                       q=Q, r=R, rho=RHO, n_envs=1, seed=0)
        b = env.baselines(s_e=S_E)
        names.append(name)

        # Constant matrices, copied off the reference object so the shipped
        # bytes are identical to the ones GLEBench steps with.
        out[f"{name}__F"] = env.F
        out[f"{name}__G"] = env.G
        out[f"{name}__Sd"] = env.Sd
        out[f"{name}__Lw"] = env.Lw
        out[f"{name}__L0"] = env.L0
        out[f"{name}__scalars"] = np.array(
            [h, Q, R, THETA, RHO, c, gamma, env.nx, EPISODE_LEN], dtype=np.float64)
        out[f"{name}__baselines"] = np.array(
            [b["J_opt"], b["k_ml"], b["J_ml"], b["k_AC"], b["J_AC"], b["rThK0"]],
            dtype=np.float64)

        print(f"{name:16} {b['J_opt']:8.4f} {b['k_ml']:8.3f} {b['J_ml']:8.4f} "
              f"{b['k_AC']:9.3f} {b['J_AC']:8.4f} {b['rThK0']:8.4f}")

        # Cross-check demanded by the protocol: the cost ceiling law.
        if abs(b["rThK0"] - 0.3000) > 5e-5:
            discrepancies.append(
                f"{name}: rThK0 = {b['rThK0']:.6f}, expected 0.3000")

        # Loud comparison against the design doc's table.
        ref = DESIGN_DOC_TABLE[name]
        got = (b["J_opt"], b["k_ml"], b["J_ml"], b["k_AC"], b["J_AC"])
        for label, g, e in zip(("J_opt", "k_ml", "J_ml", "k_AC", "J_AC"),
                               got, ref):
            tol = 5e-4 * max(1.0, abs(e))
            if abs(g - e) > tol:
                discrepancies.append(
                    f"{name}: {label} generated {g:.5f}, design doc says "
                    f"{e:.5f}, difference {g - e:+.5f}")

    out["__names"] = np.array(names)
    path = os.path.join(ROOT, "harness", "gleam_instances.npz")
    np.savez(path, **out)
    print(f"\nwrote {path}")
    print(f"  {len(names)} instances, {os.path.getsize(path)} bytes, "
          f"loads with numpy alone")

    print("\n--- cross-check: rThK0 must be 0.3000 for every instance")
    for name, *_ in INSTANCES:
        v = out[f"{name}__baselines"][5]
        print(f"    {name:16} rThK0 = {v:.4f}")

    print("\n--- comparison against the phase2-design.md table")
    if discrepancies:
        print("    DISCREPANCIES FOUND. Reporting loudly, nothing suppressed:")
        for d in discrepancies:
            print(f"      {d}")
    else:
        print("    every generated value matches the design doc to 5e-4")
    return len(discrepancies)


if __name__ == "__main__":
    sys.exit(1 if build() else 0)
