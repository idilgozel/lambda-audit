"""Preregistration E11: the closed-loop POPGym test, positive side of the scope law.

FROZEN 2026-08-18, BEFORE ANY E11 RUN EXISTS ANYWHERE. Verified mechanically:

    python3 prereg_e11.py --check-clean results/results/results_e11.jsonl

refuses if E11 rows already exist. Scoring is in this file.

WHY E11 EXISTS
--------------
The scope law gives the confound a computable boundary: it requires actions to
influence the hidden state. The pilot tested POPGym only on that boundary's
NEGATIVE side (RepeatPrevious is open-loop: the deck does not care what the
agent answers) and the registered no-effect outcome (G2) is the control arm.
E11 tests the POSITIVE side on the same third-party benchmark suite:
BattleshipEasy, where firing changes the guessed-set and the information
state, hidden information persists for the entire episode, and the
correlation time is therefore the episode length itself.

THE ENVIRONMENT, AND ITS VERIFICATION
-------------------------------------
popgym BattleshipEasy (8x8, ships 2,3,3,4), reimplemented natively in
harness/envs_native.py to keep the cluster dependency-free, and verified
BITWISE against the reference implementation before any run: 200 seeded
boards identical, 12,800 steps of (obs, reward, terminated, truncated)
identical, unseeded-reset RNG stream continuation identical
(harness/test_battleship_equivalence.py). Two documented interface
adaptations, ours: the MultiDiscrete action is flattened to Discrete(64)
(bijection), and the previous action is folded into the observation exactly
as popgym's obs_requires_prev_action flag and their PreviousAction wrapper
intend. The agent-facing observation is [hit, onehot8(prev_row),
onehot8(prev_col)].

THE KNEE ARITHMETIC, STATED BEFORE THE DATA
--------------------------------------------
Hidden information (ship placement) persists all episode: tau = 64 steps.
The bootstrap horizon is (1 - gamma*lambda)^-1 with gamma = 0.99:

    lambda   0.9    0.95   0.98   0.99   0.995   0.999   1.0
    horizon  9.2    16.8   33.6   50.3   66.9    91.0    100.0

Horizon = tau at lambda = 0.99432. The community-default lambda = 0.95 sits
at a horizon of 17 steps against a 64-step task: DEEP below the knee. The
benchmark's own reference setting, lambda = 1.0, sits above it. That is the
audit's practical claim, instantiated on somebody else's benchmark.

SCRIPTED REFERENCE ANCHORS (frozen; generated by 20,000-episode Monte Carlo,
episode seeds 1,000,000+, action-stream seed 42, analysis/e11_baselines.py):

    uniform random (with repeats)      mean -0.4479   IQM -0.4447
    no-repeat (fired-set memory)       mean +0.0771   IQM +0.0568
    no-repeat + adjacency targeting    mean +0.4118   IQM +0.4135

DESIGN NOTE, recorded before data. A memoryless policy seeing the previous
action CAN avoid refiring without memory, by chaining a fixed scan cycle
(prev cell -> next cell). The no-repeat anchor is therefore NOT a memory
ceiling for the mlp; the value of memory on this task lives in targeting
after hits and in placement inference, i.e. between +0.08 and +0.41. This
was noticed at design time, not discovered after the data.

CAPABILITY GATES, scored first. A dead instrument must not masquerade as a
negative result.

  G11a  mlp IQM deployed return at lambda = 1.0  >= -0.35
        (clears the uniform floor by ~0.10: the memoryless arm has learned
        something, so a step DOWN from it is measurable. If G11a fails,
        P12.1 and P12.3 are NOT SCORED and E11 reports floor saturation.)
  G11b  gru128 IQM deployed return at lambda = 1.0  >= +0.02
        (strictly better than firing every square: the memory arm is using
        memory. If G11b fails, P12.2 and P12.3 are NOT SCORED.)

THE REGISTERED PREDICTIONS
--------------------------
Seed-level bootstrap over the 5 seeds per cell, 10,000 draws, bootstrap seed
20260818, 95 percent intervals — the E9 machinery, reused unchanged.
LOW = {0.9, 0.95} (horizons 9-17, deep below knee), HIGH = {0.999, 1.0}
(horizons 91-100, above knee). Groups frozen here.

P12.1  The memoryless architecture steps DOWN below the knee:
       IQM_mlp(LOW) - IQM_mlp(HIGH) is negative with CI excluding zero.
P12.2  The memory architecture does not:
       IQM_gru(LOW) - IQM_gru(HIGH) has CI containing zero.
P12.3  THE HEADLINE. The measured memory advantage is inflated at the
       community default: gap(lambda) = IQM_gru - IQM_mlp, and
       gap(0.95) - gap(1.0) is positive with CI excluding zero.
       This is the "architecture rankings are not transportable across the
       bootstrap horizon" claim, measured on the positive side of the scope
       law, on a third-party benchmark task.

PRE-DATA EXPECTATION, exploratory, NOT scored: the mlp degradation onset
bracket should contain lambda_knee = 0.99432, i.e. onset between 0.99 and
0.995 on this grid. Stated so the location claim is prospective if examined.

HOW A MISS IS READ, fixed in advance. P12.1 failing with gates passed means
the below-knee damage does not transfer to this discrete, sparse-reward,
closed-loop task at 15M steps — a scope restriction on the empirical claim,
reported as such. P12.2 failing (gru harmed too) breaks the
architecture-selectivity of the effect and P12.3 loses its interpretation:
both are then reported as failures. P12.3 is the paper's transportability
sentence; it is not rescued by post-hoc regrouping of lambdas.
"""
import json, math, random, sys

FROZEN_ON = "2026-08-18"
ENV = "BattleshipEasy"
LAMBDAS = [0.8, 0.9, 0.95, 0.98, 0.99, 0.995, 0.999, 1.0]
SEEDS = (1, 2, 3, 4, 5)
LOW = [0.9, 0.95]
HIGH = [0.999, 1.0]
GAP_AT = (0.95, 1.0)
G11A_MIN = -0.35
G11B_MIN = 0.02
BOOT_N = 10_000
BOOT_SEED = 20260818
CI = 95.0
ANCHORS = {"uniform": -0.4479, "no_repeat": 0.0771, "hunt_target": 0.4118}
LAMBDA_KNEE = 0.99432


def _assert_frozen():
    ok = (LOW == [0.9, 0.95] and HIGH == [0.999, 1.0] and BOOT_SEED == 20260818
          and len(LAMBDAS) == 8 and FROZEN_ON == "2026-08-18")
    if not ok:
        raise SystemExit("PREREG NOT FROZEN OR TAMPERED. Do not score.")


def load(path):
    return [json.loads(l) for l in open(path) if l.strip()]


def cell(rows, arch, lam):
    return [float(r["deployed_return"]) for r in rows
            if r.get("env") == ENV and r.get("arch") == arch
            and r.get("seed") in SEEDS
            and math.isclose(float(r.get("lam", -1)), lam)
            and r.get("deployed_return") is not None]


def iqm(xs):
    xs = sorted(xs); n = len(xs); lo, hi = n // 4, n - n // 4
    mid = xs[lo:hi] if hi > lo else xs
    return sum(mid) / len(mid)


def _boot_diff(rng, cells_a, cells_b):
    """bootstrap the difference of group IQMs; cells are lists of seed-lists."""
    out = []
    for _ in range(BOOT_N):
        ga = [iqm([c[rng.randrange(len(c))] for _ in c]) for c in cells_a]
        gb = [iqm([c[rng.randrange(len(c))] for _ in c]) for c in cells_b]
        out.append(sum(ga) / len(ga) - sum(gb) / len(gb))
    out.sort()
    lo = out[int(len(out) * (100 - CI) / 200)]
    hi = out[int(len(out) * (1 - (100 - CI) / 200)) - 1]
    return lo, hi


def check_clean(path):
    _assert_frozen()
    try:
        rows = load(path)
    except FileNotFoundError:
        print(f"CLEAN: {path} does not exist. Freeze is legitimate.")
        return 0
    n = sum(1 for r in rows if r.get("env") == ENV)
    print(f"{'NOT CLEAN' if n else 'CLEAN'}: {n} {ENV} rows in {path}.")
    return 2 if n else 0


def score(path):
    _assert_frozen()
    rows = load(path)
    v = {}
    mlp1 = cell(rows, "mlp", 1.0)
    gru1 = cell(rows, "gru128", 1.0)
    g11a = bool(mlp1) and iqm(mlp1) >= G11A_MIN
    g11b = bool(gru1) and iqm(gru1) >= G11B_MIN
    print(f"G11a mlp(1.0) IQM {iqm(mlp1) if mlp1 else float('nan'):+.4f} "
          f"(>= {G11A_MIN}) -> {'PASS' if g11a else 'FAIL'}")
    print(f"G11b gru(1.0) IQM {iqm(gru1) if gru1 else float('nan'):+.4f} "
          f"(>= {G11B_MIN}) -> {'PASS' if g11b else 'FAIL'}")
    v["G11a"], v["G11b"] = g11a, g11b

    def contrast(arch):
        lo_cells = [cell(rows, arch, l) for l in LOW]
        hi_cells = [cell(rows, arch, l) for l in HIGH]
        if any(not c for c in lo_cells + hi_cells):
            return None
        point = (sum(iqm(c) for c in lo_cells) / len(lo_cells)
                 - sum(iqm(c) for c in hi_cells) / len(hi_cells))
        rng = random.Random(BOOT_SEED)
        lo, hi = _boot_diff(rng, lo_cells, hi_cells)
        return point, lo, hi

    if g11a:
        r = contrast("mlp")
        if r:
            p, lo, hi = r
            ok = p < 0 and hi < 0
            print(f"P12.1 mlp LOW-HIGH {p:+.4f}, CI [{lo:+.4f}, {hi:+.4f}] "
                  f"-> {'PASS' if ok else 'FAIL'}")
            v["P12.1"] = ok
    else:
        print("P12.1 NOT SCORED (G11a failed: floor saturation)")

    if g11b:
        r = contrast("gru128")
        if r:
            p, lo, hi = r
            ok = lo <= 0 <= hi
            print(f"P12.2 gru LOW-HIGH {p:+.4f}, CI [{lo:+.4f}, {hi:+.4f}] "
                  f"-> {'PASS' if ok else 'FAIL'}")
            v["P12.2"] = ok
    else:
        print("P12.2 NOT SCORED (G11b failed)")

    if g11a and g11b:
        l_gap, l_ref = GAP_AT
        gcell = lambda lam: [cell(rows, "gru128", lam)]
        mcell = lambda lam: [cell(rows, "mlp", lam)]
        if all(c[0] for c in (gcell(l_gap), mcell(l_gap), gcell(l_ref), mcell(l_ref))):
            gap_a = iqm(gcell(l_gap)[0]) - iqm(mcell(l_gap)[0])
            gap_b = iqm(gcell(l_ref)[0]) - iqm(mcell(l_ref)[0])
            rng = random.Random(BOOT_SEED + 1)
            diffs = []
            ga, ma, gb, mb = gcell(l_gap)[0], mcell(l_gap)[0], gcell(l_ref)[0], mcell(l_ref)[0]
            for _ in range(BOOT_N):
                d = ((iqm([ga[rng.randrange(len(ga))] for _ in ga])
                      - iqm([ma[rng.randrange(len(ma))] for _ in ma]))
                     - (iqm([gb[rng.randrange(len(gb))] for _ in gb])
                        - iqm([mb[rng.randrange(len(mb))] for _ in mb])))
                diffs.append(d)
            diffs.sort()
            lo = diffs[int(BOOT_N * (100 - CI) / 200)]
            hi = diffs[int(BOOT_N * (1 - (100 - CI) / 200)) - 1]
            ok = gap_a - gap_b > 0 and lo > 0
            print(f"P12.3 gap({l_gap}) {gap_a:+.4f} vs gap({l_ref}) {gap_b:+.4f}, "
                  f"inflation {gap_a-gap_b:+.4f}, CI [{lo:+.4f}, {hi:+.4f}] "
                  f"-> {'PASS' if ok else 'FAIL'}")
            v["P12.3"] = ok
    else:
        print("P12.3 NOT SCORED (a gate failed)")

    print()
    print("VERDICTS:", {k: ("PASS" if b else "FAIL") for k, b in v.items()})
    return 0


def main(argv):
    _assert_frozen()
    if len(argv) > 2 and argv[1] == "--check-clean":
        return check_clean(argv[2])
    if len(argv) > 1:
        return score(argv[1])
    print(f"E11 prereg frozen {FROZEN_ON}. {ENV}, lambda grid {LAMBDAS}, "
          f"5 seeds, gates G11a/G11b, predictions P12.1-P12.3. "
          f"Knee predicted at lambda = {LAMBDA_KNEE}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
