def predicted_bracket(name):
    """The two adjacent grid lambdas the onset must fall between, or None."""
    lam_star = PREDICTIONS[name][2]
    if lam_star is None:
        return None
    lo = max([g for g in GRID if g < lam_star], default=None)
    hi = min([g for g in GRID if g >= lam_star], default=None)
    return (lo, hi)


